<?php

namespace XmlBeans\Compiler;

use XmlBeans\Common\QName;
use XmlBeans\Schema\BuiltinTypeSystem;
use XmlBeans\SchemaProperty;
use XmlBeans\SchemaType;
use XmlBeans\SchemaTypeSystem;

/**
 * Generates PHP class files from a compiled SchemaTypeSystem.
 * Equivalent to scomp code generation in Apache XMLBeans.
 *
 * Each global complex type gets a class with typed getters/setters.
 * Each global element gets a document class.
 * Simple type restrictions get typed value objects.
 */
class PhpCodeGenerator
{
    /** @var SchemaTypeSystem */
    private $typeSystem;

    /** @var string */
    private $namespace;

    /** @var string */
    private $outputDir;

    /** @var array Map of XSD type => PHP type hint */
    private static $typeMap = [
        'string' => 'string',
        'normalizedString' => 'string',
        'token' => 'string',
        'language' => 'string',
        'Name' => 'string',
        'NCName' => 'string',
        'ID' => 'string',
        'IDREF' => 'string',
        'NMTOKEN' => 'string',
        'anyURI' => 'string',
        'boolean' => 'bool',
        'int' => 'int',
        'integer' => 'int',
        'long' => 'int',
        'short' => 'int',
        'byte' => 'int',
        'unsignedInt' => 'int',
        'unsignedLong' => 'int',
        'unsignedShort' => 'int',
        'unsignedByte' => 'int',
        'nonNegativeInteger' => 'int',
        'positiveInteger' => 'int',
        'nonPositiveInteger' => 'int',
        'negativeInteger' => 'int',
        'float' => 'float',
        'double' => 'float',
        'decimal' => 'float',
        'date' => 'string',
        'dateTime' => 'string',
        'time' => 'string',
        'duration' => 'string',
        'hexBinary' => 'string',
        'base64Binary' => 'string',
        'QName' => 'string',
        'anyType' => '',
        'anySimpleType' => 'string',
    ];

    /**
     * @param SchemaTypeSystem $typeSystem
     */
    public function __construct(SchemaTypeSystem $typeSystem)
    {
        $this->typeSystem = $typeSystem;
    }

    /**
     * Generate PHP classes into the output directory.
     *
     * @param string $outputDir
     * @param string $namespace PHP namespace for generated classes
     * @return string[] List of generated file paths
     */
    public function generate($outputDir, $namespace = 'Generated')
    {
        $this->outputDir = rtrim($outputDir, '/\\');
        $this->namespace = $namespace;

        if (!is_dir($this->outputDir)) {
            mkdir($this->outputDir, 0755, true);
        }

        $generatedFiles = [];

        // Generate classes for global types
        foreach ($this->typeSystem->getGlobalTypes() as $type) {
            $name = $type->getName();
            if (!$name || $type->isBuiltinType()) {
                continue;
            }
            $file = $this->generateTypeClass($type);
            if ($file) {
                $generatedFiles[] = $file;
            }
        }

        // Generate document classes for global elements
        foreach ($this->typeSystem->getDocumentTypes() as $docType) {
            $file = $this->generateDocumentClass($docType);
            if ($file) {
                $generatedFiles[] = $file;
            }
        }

        return $generatedFiles;
    }

    /**
     * Generate a class for a global type.
     *
     * @param SchemaType $type
     * @return string|null
     */
    private function generateTypeClass(SchemaType $type)
    {
        $name = $type->getName();
        if (!$name) {
            return null;
        }

        $className = $this->toClassName($name->getLocalPart());
        $type->setPhpClassName($this->namespace . '\\' . $className);

        $code = "<?php\n\n";
        $code .= "namespace {$this->namespace};\n\n";
        $code .= "use XmlBeans\\Binding\\XmlObjectBase;\n";
        $code .= "use XmlBeans\\SchemaType;\n";
        $code .= "use DOMNode;\n\n";

        // Determine parent class
        $parentClass = 'XmlObjectBase';
        $baseType = $type->getBaseType();
        if ($baseType && $baseType->getName() && !$baseType->isBuiltinType()) {
            $parentClass = $this->toClassName($baseType->getName()->getLocalPart());
        }

        $code .= "/**\n";
        $code .= " * Generated class for {$name}\n";
        if ($type->isSimpleType()) {
            $code .= " * Simple type" . ($type->getBaseType() ? " (restriction of {$type->getBaseType()})" : "") . "\n";
        } else {
            $code .= " * Complex type\n";
        }
        $code .= " *\n";
        $code .= " * @generated by php-xmlbeans schema compiler\n";
        $code .= " */\n";
        $code .= "class {$className} extends {$parentClass}\n{\n";

        // Enumeration constants
        $enums = $type->getEnumerationValues();
        if (!empty($enums)) {
            foreach ($enums as $enum) {
                $constName = strtoupper(preg_replace('/[^a-zA-Z0-9_]/', '_', $enum));
                $code .= "    const VALUE_{$constName} = '{$enum}';\n";
            }
            $code .= "\n";
        }

        // Constructor
        $code .= '    /**' . "\n";
        $code .= '     * @param DOMNode|null $node' . "\n";
        $code .= '     * @param SchemaType|null $schemaType' . "\n";
        $code .= '     */' . "\n";
        $code .= '    public function __construct(DOMNode $node = null, SchemaType $schemaType = null)' . "\n";
        $code .= '    {' . "\n";
        $code .= '        parent::__construct($node, $schemaType);' . "\n";
        $code .= '    }' . "\n\n";

        // Element getters/setters
        foreach ($type->getElementProperties() as $prop) {
            $code .= $this->generatePropertyAccessors($prop);
        }

        // Attribute getters/setters
        foreach ($type->getAttributeProperties() as $prop) {
            $code .= $this->generatePropertyAccessors($prop);
        }

        // Simple type value accessor
        if ($type->isSimpleType()) {
            $phpType = $this->resolvePhpType($type);
            $code .= "    /**\n";
            $code .= "     * Get the typed value.\n";
            $code .= '     * @return ' . $phpType . "\n";
            $code .= "     */\n";
            $code .= '    public function getValue()' . "\n";
            $code .= '    {' . "\n";
            $code .= $this->generateValueConversion($type, '$this->getStringValue()');
            $code .= '    }' . "\n\n";

            $code .= "    /**\n";
            $code .= "     * Set the typed value.\n";
            $code .= '     * @param ' . $phpType . ' $value' . "\n";
            $code .= "     */\n";
            $code .= '    public function setValue($value)' . "\n";
            $code .= '    {' . "\n";
            $code .= '        $this->setStringValue((string) $value);' . "\n";
            $code .= '    }' . "\n\n";
        }

        // isValid helper
        if (!empty($enums)) {
            $code .= "    /**\n";
            $code .= "     * Check if a value is valid for this type.\n";
            $code .= '     * @param string $value' . "\n";
            $code .= "     * @return bool\n";
            $code .= "     */\n";
            $code .= '    public static function isValidValue($value)' . "\n";
            $code .= '    {' . "\n";
            $code .= '        return in_array($value, [' . "\n";
            foreach ($enums as $enum) {
                $code .= "            '{$this->escapeString($enum)}',\n";
            }
            $code .= "        ], true);\n";
            $code .= "    }\n\n";
        }

        $code .= "}\n";

        $filepath = $this->outputDir . '/' . $className . '.php';
        file_put_contents($filepath, $code);
        return $filepath;
    }

    /**
     * Generate a document class for a global element.
     *
     * @param SchemaType $docType
     * @return string|null
     */
    private function generateDocumentClass(SchemaType $docType)
    {
        $name = $docType->getName();
        if (!$name) {
            return null;
        }

        $className = $this->toClassName($name->getLocalPart()) . 'Document';
        $docType->setPhpClassName($this->namespace . '\\' . $className);

        $code = "<?php\n\n";
        $code .= "namespace {$this->namespace};\n\n";
        $code .= "use XmlBeans\\Binding\\XmlObjectBase;\n";
        $code .= "use XmlBeans\\SchemaType;\n";
        $code .= "use DOMNode;\n\n";

        $code .= "/**\n";
        $code .= " * Document class for global element '{$name->getLocalPart()}'\n";
        $code .= " *\n";
        $code .= " * @generated by php-xmlbeans schema compiler\n";
        $code .= " */\n";
        $code .= "class {$className} extends XmlObjectBase\n{\n";

        // Parse factory
        $code .= "    /**\n";
        $code .= "     * Parse XML string into this document type.\n";
        $code .= "     *\n";
        $code .= '     * @param string $xml' . "\n";
        $code .= '     * @param SchemaType|null $type' . "\n";
        $code .= '     * @param \XmlBeans\XmlOptions|null $options' . "\n";
        $code .= "     * @return static\n";
        $code .= "     */\n";
        $code .= '    public static function parse($xml, $type = null, $options = null)' . "\n";
        $code .= '    {' . "\n";
        $code .= '        return parent::parse($xml, $type, $options);' . "\n";
        $code .= '    }' . "\n\n";

        // Element accessors
        foreach ($docType->getElementProperties() as $prop) {
            $code .= $this->generatePropertyAccessors($prop);
        }

        $code .= "}\n";

        $filepath = $this->outputDir . '/' . $className . '.php';
        file_put_contents($filepath, $code);
        return $filepath;
    }

    /**
     * Generate getter/setter for a SchemaProperty.
     *
     * @param SchemaProperty $prop
     * @return string
     */
    private function generatePropertyAccessors(SchemaProperty $prop)
    {
        $code = '';
        $name = $prop->getName()->getLocalPart();
        $phpName = $this->toPascalCase($name); // Always PascalCase for methods
        $phpType = $this->resolvePhpTypeForProperty($prop);
        $ns = $prop->getName()->getNamespaceURI();
        $nsArg = $ns ? "'{$ns}'" : "''";
        $isArray = $prop->isArray();
        $isAttr = $prop->isAttribute();

        $D = '$'; // Dollar sign for generated code

        if ($isAttr) {
            // Attribute getter
            $code .= "    /**\n";
            $code .= "     * Get the '" . $name . "' attribute.\n";
            $code .= "     * @return " . $phpType . "|null\n";
            $code .= "     */\n";
            $code .= '    public function get' . $phpName . "()\n";
            $code .= "    {\n";
            $code .= '        return ' . $D . 'this->getAttributeValue(\'' . $name . '\', ' . $nsArg . ");\n";
            $code .= "    }\n\n";

            // Attribute setter
            $code .= "    /**\n";
            $code .= "     * Set the '" . $name . "' attribute.\n";
            $code .= "     * @param " . $phpType . ' ' . $D . "value\n";
            $code .= "     */\n";
            $code .= '    public function set' . $phpName . '(' . $D . "value)\n";
            $code .= "    {\n";
            $code .= '        ' . $D . 'this->setAttributeValue(\'' . $name . '\', (string) ' . $D . 'value, ' . $nsArg . ");\n";
            $code .= "    }\n\n";
        } elseif ($isArray) {
            // Array getter
            $code .= "    /**\n";
            $code .= "     * Get all '" . $name . "' elements.\n";
            $code .= "     * @return XmlObjectBase[]\n";
            $code .= "     */\n";
            $code .= '    public function get' . $phpName . "Array()\n";
            $code .= "    {\n";
            $code .= '        return ' . $D . 'this->getChildObjectArray(\'' . $name . '\', ' . $nsArg . ");\n";
            $code .= "    }\n\n";

            // Indexed getter
            $code .= "    /**\n";
            $code .= "     * Get '" . $name . "' element at index.\n";
            $code .= "     * @param int " . $D . "index\n";
            $code .= "     * @return XmlObjectBase|null\n";
            $code .= "     */\n";
            $code .= '    public function get' . $phpName . '(' . $D . "index = 0)\n";
            $code .= "    {\n";
            $code .= '        ' . $D . 'arr = ' . $D . 'this->get' . $phpName . "Array();\n";
            $code .= '        return isset(' . $D . 'arr[' . $D . 'index]) ? ' . $D . 'arr[' . $D . "index] : null;\n";
            $code .= "    }\n\n";

            // Count
            $code .= "    /**\n";
            $code .= "     * Get the count of '" . $name . "' elements.\n";
            $code .= "     * @return int\n";
            $code .= "     */\n";
            $code .= '    public function sizeOf' . $phpName . "Array()\n";
            $code .= "    {\n";
            $code .= '        return count(' . $D . 'this->getChildElements(\'' . $name . '\', ' . $nsArg . "));\n";
            $code .= "    }\n\n";

            // Add
            $code .= "    /**\n";
            $code .= "     * Add a new '" . $name . "' element.\n";
            $code .= "     * @param string " . $D . "value\n";
            $code .= "     * @return \\DOMElement\n";
            $code .= "     */\n";
            $code .= '    public function addNew' . $phpName . '(' . $D . "value = '')\n";
            $code .= "    {\n";
            $code .= '        return ' . $D . 'this->addChildElement(\'' . $name . '\', ' . $D . 'value, ' . $nsArg . ");\n";
            $code .= "    }\n\n";
        } else {
            // Scalar getter
            $code .= "    /**\n";
            $code .= "     * Get the '" . $name . "' element text.\n";
            $code .= "     * @return " . $phpType . "|null\n";
            $code .= "     */\n";
            $code .= '    public function get' . $phpName . "()\n";
            $code .= "    {\n";
            $code .= '        return ' . $D . 'this->getChildText(\'' . $name . '\', ' . $nsArg . ");\n";
            $code .= "    }\n\n";

            // Scalar setter
            $code .= "    /**\n";
            $code .= "     * Set the '" . $name . "' element text.\n";
            $code .= "     * @param " . $phpType . ' ' . $D . "value\n";
            $code .= "     */\n";
            $code .= '    public function set' . $phpName . '(' . $D . "value)\n";
            $code .= "    {\n";
            $code .= '        ' . $D . 'this->setChildText(\'' . $name . '\', (string) ' . $D . 'value, ' . $nsArg . ");\n";
            $code .= "    }\n\n";

            // isSet / unset
            $code .= "    /**\n";
            $code .= "     * Check if '" . $name . "' element is set.\n";
            $code .= "     * @return bool\n";
            $code .= "     */\n";
            $code .= '    public function isSet' . $phpName . "()\n";
            $code .= "    {\n";
            $code .= '        return ' . $D . 'this->getChildElement(\'' . $name . '\', ' . $nsArg . ") !== null;\n";
            $code .= "    }\n\n";

            $code .= "    /**\n";
            $code .= "     * Remove the '" . $name . "' element.\n";
            $code .= "     * @return bool\n";
            $code .= "     */\n";
            $code .= '    public function unset' . $phpName . "()\n";
            $code .= "    {\n";
            $code .= '        return ' . $D . 'this->removeChildElement(\'' . $name . '\', ' . $nsArg . ");\n";
            $code .= "    }\n\n";
        }

        return $code;
    }

    /**
     * Resolve a PHP type hint for a SchemaProperty.
     *
     * @param SchemaProperty $prop
     * @return string
     */
    private function resolvePhpTypeForProperty(SchemaProperty $prop)
    {
        $type = $prop->getType();
        if ($type) {
            return $this->resolvePhpType($type);
        }
        $typeName = $prop->getTypeName();
        if ($typeName) {
            // Strip prefix
            $local = $typeName;
            if (strpos($typeName, ':') !== false) {
                list(, $local) = explode(':', $typeName, 2);
            }
            if (isset(self::$typeMap[$local])) {
                return self::$typeMap[$local] ?: 'mixed';
            }
        }
        return 'string';
    }

    /**
     * Resolve the PHP type for a SchemaType.
     *
     * @param SchemaType $type
     * @return string
     */
    private function resolvePhpType(SchemaType $type)
    {
        if ($type->isBuiltinType()) {
            $name = $type->getName();
            if ($name && isset(self::$typeMap[$name->getLocalPart()])) {
                return self::$typeMap[$name->getLocalPart()] ?: 'mixed';
            }
        }

        if ($type->isSimpleType()) {
            $base = $type->getBaseType();
            if ($base) {
                return $this->resolvePhpType($base);
            }
        }

        return 'string';
    }

    /**
     * Generate value conversion code for getValue().
     *
     * @param SchemaType $type
     * @param string     $expr
     * @return string
     */
    private function generateValueConversion(SchemaType $type, $expr)
    {
        $phpType = $this->resolvePhpType($type);
        switch ($phpType) {
            case 'int':
                return '        return (int) trim(' . $expr . ');' . "\n";
            case 'float':
                return '        return (float) trim(' . $expr . ');' . "\n";
            case 'bool':
                return '        $v = trim(' . $expr . ');' . "\n" .
                       '        return $v === \'true\' || $v === \'1\';' . "\n";
            default:
                return '        return trim(' . $expr . ');' . "\n";
        }
    }

    /**
     * Convert a schema name to a valid PHP class name.
     *
     * @param string $name
     * @return string
     */
    private function toClassName($name)
    {
        $name = str_replace(['-', '.', '/', '\\'], ' ', $name);
        $name = str_replace(' ', '', ucwords($name));
        // Ensure starts with a letter
        if (preg_match('/^\d/', $name)) {
            $name = 'X' . $name;
        }
        return $name;
    }

    /**
     * @param string $name
     * @return string
     */
    private function toPascalCase($name)
    {
        $name = str_replace(['-', '_', '.'], ' ', $name);
        return str_replace(' ', '', ucwords($name));
    }

    /**
     * @param string $str
     * @return string
     */
    private function escapeString($str)
    {
        return addcslashes($str, "'\\");
    }
}
